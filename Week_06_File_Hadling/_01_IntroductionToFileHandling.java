public class _01_IntroductionToFileHandling {

    public static void main(String[] args) {

        System.out.println("========== JAVA FILE HANDLING ==========\n");

        System.out.println("File Handling is used to store data permanently.");

        System.out.println("\nExamples:");
        System.out.println("- Student Records");
        System.out.println("- Employee Details");
        System.out.println("- Configuration Files");
        System.out.println("- Bank Transactions");
        System.out.println("- Application Logs");

        System.out.println("\nCharacter Stream -> Text Files (.txt, .java, .csv)");
        System.out.println("Byte Stream      -> Images, PDF, Videos");

        System.out.println("\nInput  -> Read Data from File");
        System.out.println("Output -> Write Data to File");

    }

}